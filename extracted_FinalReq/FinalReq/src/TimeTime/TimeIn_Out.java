    public void searchData(String in) {
        ObjectContainer mj = Db4oEmbedded.openFile("Attendance.db4o");

        try {
            String inp = in.toLowerCase();

            ObjectSet result = mj.query(new Predicate<Attendance>() {

                public boolean match(Attendance et) {
                    return (et.getId().toLowerCase().contains(inp) || et.getName().toLowerCase().contains(inp) || et.getDep().toLowerCase().contains(inp) || et.getIn().toLowerCase().contains(inp) || et.getOut().toLowerCase().contains(inp));
                }
            });
            clearTable();

            while (result.hasNext()) {
                Attendance ui1 = new Attendance();
                ui1 = (Attendance) result.next();

                ((DefaultTableModel) Table.getModel()).addRow(new Object[]{ui1.getId(), ui1.getName(), ui1.getDep(), ui1.getIn(), ui1.getOut()});
            }

        } catch (Exception e) {
            System.out.println(e);
        } finally {
            mj.close();
        }
    }
