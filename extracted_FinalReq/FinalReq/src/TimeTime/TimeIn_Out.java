    public void timeIn() {
        ObjectContainer mj = Db4oEmbedded.openFile("Attendance.db4o");
        try {
            String employeeID = CID.getText(); // Assuming CID is a JTextField
            String employeeName = name.getText(); // Assuming name is a JTextField
            String employeeDep = Dep.getText(); // Assuming Dep is a JTextField

            Attendance data = new Attendance(employeeID, employeeName, employeeDep, getCurrentDateTime(), "");

            mj.store(data);
            JOptionPane.showMessageDialog(null, "Data Successfully added!", "Successful", JOptionPane.INFORMATION_MESSAGE);
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error recording Time In", "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            if (mj != null) {
                mj.close();
                clearTable();
                retrieveData();
            }
        }
    }

    private String getCurrentDateTime() {
        LocalDateTime currentDateTime = LocalDateTime.now();
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("yyyy-MM-dd hh:mm:ss a"); // Use 'hh' for 12-hour format
        return currentDateTime.format(formatter);
    }

    public void timeOut() {

        ObjectContainer mj = Db4oEmbedded.openFile("Attendance.db4o");
        try {
            String employeeID = CID.getText(); // Assuming CID is a JTextField

            // Create a template with the employee ID
            Attendance template = new Attendance(employeeID);

            // Query the database to get all time-in records for the employee
            ObjectSet<Attendance> result = mj.queryByExample(template);

            if (result.isEmpty()) {
                JOptionPane.showMessageDialog(null, "No time-in record found for the employee ID", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // Find the latest time-in record
            Attendance latestTimeInData = result.stream()
                    .max(Comparator.comparing(Attendance::getIn))
                    .orElse(null);

            // Update the time-out field with the current date and time
            latestTimeInData.setData(getCurrentDateTime());
            mj.store(latestTimeInData);

            JOptionPane.showMessageDialog(null, "Successfully Timed out!", "Update Data", JOptionPane.INFORMATION_MESSAGE);
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error recording Time Out", "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            if (mj != null) {
                mj.close();
                clearTable();
                retrieveData();
            }
        }
    }

    public void clearTable() {
        DefaultTableModel model = (DefaultTableModel) Table.getModel();
        model.setRowCount(0);
    }

    public void retrieveData() {
        ObjectContainer mj = Db4oEmbedded.openFile("Attendance.db4o");
        try {

            Attendance ui = new Attendance();
            
            ObjectSet result = mj.queryByExample(ui);
            while (result.hasNext()) {
                Attendance ui1 = new Attendance();
                ui1 = (Attendance) result.next();
                ((DefaultTableModel) Table.getModel()).addRow(new Object[]{ui1.getId(), ui1.getName(), ui1.getDep(), ui1.getIn(), ui1.getOut()});
            }
        } catch (Exception e) {
            System.out.println(e);
        } finally {
            mj.close();
        }
    }

