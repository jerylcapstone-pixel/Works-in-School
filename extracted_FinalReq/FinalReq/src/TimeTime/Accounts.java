    private void DelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DelActionPerformed
        ObjectContainer mj = Db4oEmbedded.openFile("Register.db4o");

        try {
            DataFields ui = new DataFields (id);
            ObjectSet result = mj.queryByExample(ui);

            while (result.hasNext()) {
                DataFields ui1 = new DataFields();
                ui1 = (DataFields) result.next();

                int val = JOptionPane.showConfirmDialog(null, "Want to delete " + ui1.getName() + " ?", "Delete Data", JOptionPane.YES_NO_OPTION);

                if (val == 0) {
                    mj.delete(ui1);

                    JOptionPane.showMessageDialog(null, "Data Successfully Deleted", "Data Deleted", JOptionPane.INFORMATION_MESSAGE);

                }
                return;
            }

        } catch (Exception e) {
            System.out.println(e);
        } finally {
            mj.close();
            clearTable();
            retrieveData();
            reset();
        
        }
    }
        public void addData(){
        ObjectContainer mj = Db4oEmbedded.openFile("Register.db4o");
          id = Id.getText();
         name = Name.getText();
         dep = Dep.getText();
         pass = pword.getText();
        ObjectSet<DataFields> result = mj.queryByExample(new DataFields(id));
        if (!result.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Account " + id+ " already registered!", "Registration Failed", JOptionPane.ERROR_MESSAGE);
            return;
        }

        if (id.isEmpty() || name.isEmpty() || dep.isEmpty() || pass.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Username or password cannot be empty", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
        
            DataFields ui = new DataFields (id, name, dep, pass);
            mj.store(ui);
            JOptionPane.showMessageDialog(null, "Register Success!", "Successful", JOptionPane.INFORMATION_MESSAGE);
        } catch (Exception e) {
            System.out.println(e);
        } finally {
            mj.close();
            reset();
        }
        
        

    }//GEN-LAST:event_DelActionPerformed

