    private void TableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_TableMouseClicked
   int i = Table.getSelectedRow();

        TableModel m = Table.getModel();
        String o = m.getValueAt(i, 0).toString();

        ObjectContainer mj = Db4oEmbedded.openFile("Register.db4o");

        try {
          DataFields ui = new DataFields (o);
            ObjectSet result = mj.queryByExample(ui);

            while (result.hasNext()) {
                DataFields ui1 = new DataFields();
                ui1 = (DataFields) result.next();

                
                Id.setText(ui1.getId());
                Name.setText(ui1.getName());
                Dep.setText(ui1.getDep());
                pword.setText(ui1.getPass());   
            }

        } catch (Exception e) {
            System.out.println(e);
        } finally {
            mj.close(); 
          
        }
    }//GEN-LAST:event_TableMouseClicked
public void searchData(String in) {
        ObjectContainer mj = Db4oEmbedded.openFile("Register.db4o");

        try {
            String inp = in.toLowerCase();

            ObjectSet result = mj.query(new Predicate<DataFields>() {
                
                public boolean match(DataFields et) {
                   return(et.getId().toLowerCase().contains(inp) || et.getName().toLowerCase().contains(inp)|| et.getDep().toLowerCase().contains(inp)|| et.getPass().toLowerCase().contains(inp));
                }
            });
            clearTable();

            while (result.hasNext()) {
           DataFields ui1 = new DataFields();
                ui1 = (DataFields) result.next();

                ((DefaultTableModel) Table.getModel()).addRow(new Object[]{ui1.getId(), ui1.getName(), ui1.getDep(), ui1.getPass()});
            }

        } catch (Exception e) {
            System.out.println(e);
        } finally {
            mj.close();
        }
    }

