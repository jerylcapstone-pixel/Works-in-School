public void updateProfile(String currentID, String newID, String newName, String newDep) {
        ObjectContainer db = Db4oEmbedded.openFile("Register.db4o");
        try {
            
            ObjectSet<DataFields> existingAccounts = db.queryByExample(new DataFields(newID));
            if (!existingAccounts.isEmpty()) {
                JOptionPane.showMessageDialog(null, "The new ID is already in use. Please choose a different ID.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            
            ObjectSet<DataFields> result = db.queryByExample(new DataFields(currentID));
            if (result.hasNext()) {
                DataFields account = result.next();
                
               
                account.setId(newID);
                account.setName(newName);
                account.setDep(newDep);

                
                db.store(account);
                
                JOptionPane.showMessageDialog(null, "Profile updated successfully!", "Success", JOptionPane.INFORMATION_MESSAGE);
            } else {
                    JOptionPane.showMessageDialog(null, "Account with current ID not found.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (Db4oException e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(null, "Error updating profile", "Error", JOptionPane.ERROR_MESSAGE);
        } finally {
            if (db != null) {
                db.close();
}
        }
    }

