 private void performUpdate() {
        String currentID = Retriever.getCurrentEmployeeID();
        String newID = id.getText();
        String newName = name.getText();
        String newDep = dep.getText();

        // Validate the input fields (you can customize this validation)
        if (newID.isEmpty() || newName.isEmpty() || newDep.isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please fill in all fields.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }

        updateProfile(currentID, newID, newName, newDep);

        // Refresh the table after updating the profile
        retrieveData();
    }
